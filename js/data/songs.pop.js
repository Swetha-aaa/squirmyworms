function slug(s) {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

const seen = new Set();
export const POP_SONGS = [];
for (const [title, artist, album, year] of raw) {
  if (!title) continue;
  const id = `pop:${slug(title)}--${slug(artist.split(/ ft\.| & |, /)[0])}`;
  if (seen.has(id)) continue; // duplicate entry, keep the first
  seen.add(id);
  POP_SONGS.push({
    id,
    title,
    artist,
    album,
    year,
    category: 'pop',
    artwork: null,
    audio: AUDIO_PLACEHOLDER,
  });
}
